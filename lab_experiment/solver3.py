cipher = [
    0xb2, 0x84, 0x82, 0x94,
    0x93, 0x88, 0x8f, 0x84,
    0x95, 0x92, 0xbe, 0x87,
    0x92, 0x95, 0x9a, 0x80,
    0x92, 0x92, 0xd0, 0x92,
    0x95, 0x80, 0x8f, 0x95,
    0xbe, 0x95, 0x89, 0x88,
    0xd8, 0x80, 0x9c
]

key = 0xE1
pt = bytes([b ^ key for b in cipher])
